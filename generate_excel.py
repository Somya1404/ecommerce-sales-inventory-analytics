# generate_excel.py
"""Create the Excel workbook for the e‑commerce analytics project.

- Loads the CSV files generated by `generate_data.py`.
- Writes each table to a separate sheet as an Excel Table.
- Adds calculated columns (Revenue, Discount Amount, Net Sales, Estimated Cost, Gross Profit).
- Applies data validation and conditional formatting for low‑stock warnings.
- Creates a simple summary sheet with KPI cards (using formulas).

The workbook is saved as `excel/Ecommerce_Analytics.xlsx`.
"""

import os
import openpyxl
import openpyxl.utils
import pandas as pd
from openpyxl import Workbook
from openpyxl.utils.dataframe import dataframe_to_rows
from openpyxl.worksheet.table import Table, TableStyleInfo
from openpyxl.formatting.rule import CellIsRule, FormulaRule
from openpyxl.styles import Font, PatternFill, Alignment, NamedStyle

# Paths
BASE_DIR = os.path.abspath(os.path.dirname(__file__))
DATA_DIR = os.path.join(BASE_DIR, "data")
EXCEL_DIR = os.path.join(BASE_DIR, "excel")
os.makedirs(EXCEL_DIR, exist_ok=True)

# Load CSVs
orders = pd.read_csv(os.path.join(DATA_DIR, "orders.csv"))
products = pd.read_csv(os.path.join(DATA_DIR, "products.csv"))
customers = pd.read_csv(os.path.join(DATA_DIR, "customers.csv"))
inventory = pd.read_csv(os.path.join(DATA_DIR, "inventory.csv"))
returns = pd.read_csv(os.path.join(DATA_DIR, "returns.csv"))

# Helper to write a dataframe as an Excel Table
def write_table(ws, df, table_name):
    for r in dataframe_to_rows(df, index=False, header=True):
        ws.append(r)
    tab = Table(displayName=table_name, ref=ws.dimensions)
    style = TableStyleInfo(name="TableStyleMedium9", showFirstColumn=False,
                            showLastColumn=False, showRowStripes=True, showColumnStripes=False)
    tab.tableStyleInfo = style
    ws.add_table(tab)

wb = Workbook()
# Remove the default sheet
default_ws = wb.active
wb.remove(default_ws)

# 1. Raw data sheets
sheets = {
    "Orders": (orders, "tblOrders"),
    "Products": (products, "tblProducts"),
    "Customers": (customers, "tblCustomers"),
    "Inventory": (inventory, "tblInventory"),
    "Returns": (returns, "tblReturns"),
}
for name, (df, table_name) in sheets.items():
    ws = wb.create_sheet(title=name)
    write_table(ws, df, table_name)

# 2. Calculated columns – we add them to the Orders sheet
orders_ws = wb["Orders"]
# Assuming columns are in the same order as CSV header
# Add new columns after the existing ones
new_headers = ["Revenue", "Discount Amount", "Net Sales", "Estimated Cost", "Gross Profit"]
for col_name in new_headers:
    orders_ws.cell(row=1, column=orders_ws.max_column + 1, value=col_name)

# Column letters for reference
def col_letter(col_idx):
    return openpyxl.utils.get_column_letter(col_idx)

# Get column indices for needed fields (1‑based)
header = [cell.value for cell in orders_ws[1]]
idx_qty = header.index("Quantity") + 1
idx_price = header.index("Unit Price") + 1
idx_discount = header.index("Discount") + 1
idx_product = header.index("Product ID") + 1

# Add formulas for each row (skip header)
for row in range(2, orders_ws.max_row + 1):
    qty_cell = f"{col_letter(idx_qty)}{row}"
    price_cell = f"{col_letter(idx_price)}{row}"
    discount_cell = f"{col_letter(idx_discount)}{row}"
    product_cell = f"{col_letter(idx_product)}{row}"
    # Revenue = Quantity * Unit Price
    orders_ws[f"{col_letter(orders_ws.max_column-4)}{row}"] = f"={qty_cell}*{price_cell}"
    # Discount Amount = Revenue * Discount
    orders_ws[f"{col_letter(orders_ws.max_column-3)}{row}"] = f"={col_letter(orders_ws.max_column-4)}{row}*{discount_cell}"
    # Net Sales = Revenue - Discount Amount
    orders_ws[f"{col_letter(orders_ws.max_column-2)}{row}"] = f"={col_letter(orders_ws.max_column-4)}{row}-{col_letter(orders_ws.max_column-3)}{row}"
    # Estimated Cost = Quantity * lookup Unit Cost from Products sheet
    # We'll use VLOOKUP: =VLOOKUP(ProductID,Products!$A:$G,6,FALSE)*Quantity
    orders_ws[f"{col_letter(orders_ws.max_column-1)}{row}"] = f"=VLOOKUP({product_cell},Products!$A:$G,6,FALSE)*{qty_cell}"
    # Gross Profit = Net Sales - Estimated Cost
    orders_ws[f"{col_letter(orders_ws.max_column)}{row}"] = f"={col_letter(orders_ws.max_column-2)}{row}-{col_letter(orders_ws.max_column-1)}{row}"

# 3. Simple KPI dashboard sheet
kpi_ws = wb.create_sheet(title="Dashboard")
# Define KPI cells and formulas
kpi_labels = [
    ("Total Gross Sales", "=SUM(Orders[Revenue])"),
    ("Total Net Sales", "=SUM(Orders[Net Sales])"),
    ("Total Orders", "=COUNTA(Orders[Order ID])"),
    ("Units Sold", "=SUM(Orders[Quantity])"),
    ("Gross Profit", "=SUM(Orders[Gross Profit])"),
    ("Gross Margin %", "=IF([Total Net Sales]=0,0,[Gross Profit]/[Total Net Sales])"),
    ("Return Rate %", "=IF([Units Sold]=0,0, SUM(Returns[Return Quantity])/[Units Sold])")
]
start_row = 2
for i, (label, formula) in enumerate(kpi_labels):
    row = start_row + i
    kpi_ws.cell(row=row, column=1, value=label)
    # Use structured references when possible – they work inside Excel tables.
    # For Return Rate we need a named range; we will compute using simple SUM.
    kpi_ws.cell(row=row, column=2, value=formula)
    # Style
    kpi_ws.cell(row=row, column=1).font = Font(bold=True)
    kpi_ws.cell(row=row, column=2).font = Font(color="1560BD", size=14)

# Apply some basic formatting to the dashboard
for col in [1, 2]:
    kpi_ws.column_dimensions[openpyxl.utils.get_column_letter(col)].width = 25

# Conditional formatting – Low Stock in Inventory sheet (highlight rows where Stock on Hand <= Reorder Level)
inv_ws = wb["Inventory"]
stock_col = None
reorder_col = None
for idx, cell in enumerate(inv_ws[1], start=1):
    if cell.value == "Stock on Hand":
        stock_col = idx
    if cell.value == "Reorder Level":
        reorder_col = idx
if stock_col and reorder_col:
    # Apply red fill when stock <= reorder level
    red_fill = PatternFill(start_color="FFC7CE", end_color="FFC7CE", fill_type="solid")
    formula = f"=${openpyxl.utils.get_column_letter(stock_col)}2<=${openpyxl.utils.get_column_letter(reorder_col)}2"
    inv_ws.conditional_formatting.add(f"A2:{openpyxl.utils.get_column_letter(inv_ws.max_column)}{inv_ws.max_row}",
                                   FormulaRule(formula=[formula], stopIfTrue=True, fill=red_fill))

# Save workbook
wb_path = os.path.join(EXCEL_DIR, "Ecommerce_Analytics.xlsx")
wb.save(wb_path)
print(f"Excel workbook created at {wb_path}")
